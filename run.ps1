<#
.SYNOPSIS
  Builds MW5 Save Editor as one self-contained exe, installs it to C:\Apps\Mods.MechWarrior5.SaveEditor, and
  (re)creates its Desktop and Start-menu shortcuts with the app's icon.
  It builds the latest checked-in version, not the working tree: it fetches origin, takes the newer of main and
  origin/main (origin/main when they've diverged), and builds a clean, temporary detached worktree of that commit.
  Uncommitted edits are never deployed. The shortcuts open the install folder's run.bat, rewritten on every run, which
  asks first: 1) Deploy & Run reruns this script with -Republish -Launch; 2) Run opens the installed app (deploying first
  if nothing is installed yet). This script itself never prompts, so agents and /deploy can run it unattended.
  settings.json beside the installed exe is kept across deploys.
.PARAMETER Force
  Publish even when the installed exe was already built from the same build inputs.
.PARAMETER Launch
  Open the editor when done.
.PARAMETER Republish
  Same as -Force (the launcher's Deploy & Run uses it).
.PARAMETER LauncherOnly
  Only write the launcher and point the shortcuts at it, then exit: nothing is fetched, built, stopped or installed.
#>
param([switch]$Launch, [switch]$Force, [switch]$Republish, [switch]$LauncherOnly)
$ErrorActionPreference = 'Stop'
$repo = $PSScriptRoot
$name = 'Mods.MechWarrior5.SaveEditor'
$exeName = 'MW5SaveEditor'
$title = 'MW5 Save Editor'
$apps = if (Test-Path 'C:\Apps') { 'C:\Apps' } else { Join-Path $env:LOCALAPPDATA 'Programs' }
$dest = Join-Path $apps $name
$exe = Join-Path $dest "$exeName.exe"

$launcher = Join-Path $dest 'run.bat'
New-Item -ItemType Directory -Force -Path $dest | Out-Null
$launcherText = @"
@echo off
title $title
rem Generated by $repo\run.ps1 - edits here are overwritten.
set "DEPLOY_PS1=$repo\run.ps1"
set "APP_EXE=%~dp0$exeName.exe"
echo.
echo   $title
echo     1^) Deploy ^& Run
echo     2^) Run
echo.
choice /c 12 /n /m "  Choose 1 or 2: "
if errorlevel 2 goto run
:deploy
if not exist "%DEPLOY_PS1%" (
    echo Repo not found - opening the installed copy.
    goto run
)
powershell -NoProfile -ExecutionPolicy Bypass -File "%DEPLOY_PS1%" -Republish -Launch %*
if errorlevel 1 (
    echo Redeploy failed - opening the installed copy.
    if exist "%APP_EXE%" start "" "%APP_EXE%"
    pause
)
exit /b 0
:run
if not exist "%APP_EXE%" (
    if exist "%DEPLOY_PS1%" (
        echo $title is not installed yet - deploying it first.
        goto deploy
    )
    echo $title is not installed and its repo is missing.
    pause
    exit /b 1
)
start "" "%APP_EXE%"
exit /b 0
"@ -replace "`r?`n", "`r`n"  # CRLF: cmd can miss a goto label in an LF-only batch file
# Only rewritten when it changed: the launcher is the batch file running this script, and cmd reads it as it goes.
if (-not (Test-Path $launcher) -or (Get-Content -Raw $launcher) -ne $launcherText) {
  Set-Content -LiteralPath $launcher -Value $launcherText -Encoding ascii -NoNewline
}

# A normal window (not minimized), so the launcher's menu shows.
function New-Shortcut([string]$path) {
  New-Item -ItemType Directory -Force -Path (Split-Path $path) | Out-Null
  $shell = New-Object -ComObject WScript.Shell
  $lnk = $shell.CreateShortcut($path)
  $lnk.TargetPath = $launcher
  $lnk.WorkingDirectory = $dest
  $lnk.WindowStyle = 1
  $lnk.IconLocation = "$exe,0"
  $lnk.Description = 'Edit MechWarrior 5: Mercenaries and Clans saves.'
  $lnk.Save()
  Write-Host "Shortcut $path"
}
$desktopLnk = Join-Path ([Environment]::GetFolderPath('Desktop')) "$title.lnk"
$startLnk = Join-Path ([Environment]::GetFolderPath('Programs')) "MindAttic\$title.lnk"
if ($LauncherOnly) {
  New-Shortcut $desktopLnk
  New-Shortcut $startLnk
  Write-Host "Wrote $launcher"
  return
}

# Windows PowerShell turns a native command's stderr into a terminating error under 'Stop', so git runs under 'Continue'.
function Invoke-Git { $ErrorActionPreference = 'Continue'; $out = & git -C $repo @args 2>$null; if ($LASTEXITCODE -ne 0) { return $null }; $out }
function Test-Ancestor($a, $b) { $ErrorActionPreference = 'Continue'; & git -C $repo merge-base --is-ancestor $a $b 2>$null; $LASTEXITCODE -eq 0 }

$null = Invoke-Git fetch origin --quiet
if ($LASTEXITCODE -ne 0) { Write-Host 'git fetch failed; deploying from the last fetched origin/main.' }
$local = Invoke-Git rev-parse --verify --quiet 'refs/heads/main'
$remote = Invoke-Git rev-parse --verify --quiet 'refs/remotes/origin/main'
if (-not $remote) { $commit = $local }
elseif (-not $local) { $commit = $remote }
elseif (Test-Ancestor $local $remote) { $commit = $remote }
elseif (Test-Ancestor $remote $local) { $commit = $local }
else {
  $commit = $remote
  $unpushed = Invoke-Git log --oneline "$remote..$local" -- src shared assets Directory.Build.props global.json nuget.config
  if ($unpushed) { Write-Warning "main has unpushed build changes that origin/main lacks; they aren't deployed:`n$($unpushed -join "`n")" }
}
if (-not $commit) { throw 'No main or origin/main commit to deploy.' }
$short = $commit.Substring(0, 9)

# What the exe is built from: the git tree ids of its build inputs at that commit, so a docs-only commit doesn't republish.
$buildInputs = 'src', 'shared', 'assets', 'Directory.Build.props', 'global.json', 'nuget.config'
$buildKey = ($buildInputs | ForEach-Object { "$_=$(Invoke-Git rev-parse --verify --quiet "${commit}:$_")" }) -join ';'
$stamp = Join-Path $dest 'deployed-build.txt'
$deployedKey = if (Test-Path $stamp) { (Get-Content $stamp -TotalCount 1) } else { $null }
$stale = $Force -or $Republish -or -not (Test-Path $exe) -or $deployedKey -ne $buildKey

$snapshot = $null
try {
  if ($stale) {
    $snapshot = Join-Path ([IO.Path]::GetTempPath()) "$name.deploy\$short"
    if (Test-Path $snapshot) { $null = Invoke-Git worktree remove --force $snapshot; if (Test-Path $snapshot) { Remove-Item $snapshot -Recurse -Force } }
    $null = Invoke-Git worktree prune
    $null = Invoke-Git worktree add --detach $snapshot $commit
    if ($LASTEXITCODE -ne 0) { throw "git worktree add $short failed ($LASTEXITCODE)" }

    # Publish beside the snapshot first, so a failed build leaves the installed editor (and any open one) alone.
    $staged = Join-Path $snapshot '.publish'
    Write-Host "Publishing $title at $short"
    dotnet publish (Join-Path $snapshot 'src\MechWarrior5.SaveEditor.App\MechWarrior5.SaveEditor.App.csproj') -c Release -r win-x64 --self-contained true `
      -p:PublishSingleFile=true -p:IncludeNativeLibrariesForSelfExtract=true -p:EnableCompressionInSingleFile=false `
      -p:DebugType=None -p:GenerateDocumentationFile=false -o $staged --nologo -v quiet
    if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed ($LASTEXITCODE)" }

    # Ask an open editor to close the normal way, so it can offer to save unsaved edits; never force-kill it.
    $running = @(Get-Process $exeName -ErrorAction SilentlyContinue | Where-Object { $_.Path -and $_.Path -ieq $exe })
    foreach ($p in $running) { $null = $p.CloseMainWindow() }
    foreach ($p in $running) {
      if (-not $p.WaitForExit(120000)) { throw "$title is still open (it may be asking about unsaved changes). Close it, then run this again." }
    }

    New-Item -ItemType Directory -Force $dest | Out-Null
    Write-Host "Installing to $dest"
    Copy-Item (Join-Path $staged '*') $dest -Recurse -Force
    Set-Content -Path $stamp -Encoding ascii -Value $buildKey, "commit=$commit"
  } else {
    Write-Host "$title is up to date ($short)."
  }

  New-Shortcut $desktopLnk
  New-Shortcut $startLnk
} finally {
  if ($snapshot) {
    $null = Invoke-Git worktree remove --force $snapshot
    if (Test-Path $snapshot) { Remove-Item $snapshot -Recurse -Force -ErrorAction SilentlyContinue; $null = Invoke-Git worktree prune }
  }
}

Write-Host "Installed $exe"
if ($Launch) { Start-Process $exe }
